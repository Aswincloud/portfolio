/**
 * @file vite-plugin-security-headers.js
 * @author Aswin
 * @copyright © 2025 Aswin. All rights reserved.
 * @description Emits `dist/_headers` for Cloudflare Workers static assets, with a
 * Content-Security-Policy whose inline-script hashes are computed from the actual
 * built HTML.
 *
 * Why generate rather than hand-write: a CSP that hashes inline scripts silently
 * breaks the site the moment anyone edits an inline <script> in index.html — the
 * browser blocks it and nothing in CI notices. Deriving the hashes from the build
 * output means the policy cannot drift from the page it protects.
 *
 * Note `_headers` only applies to *static asset* responses. Responses generated by
 * worker.js (i.e. /api/*) carry their own headers — see SECURITY_HEADERS there.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Third-party origins the page legitimately talks to. */
const GTM = 'https://www.googletagmanager.com';
const CHATWOOT = 'https://support.aswincloud.com';
const FONTS_CSS = 'https://fonts.googleapis.com';
const FONTS_FILES = 'https://fonts.gstatic.com';
// GA4 spreads telemetry across regional subdomains (region1.google-analytics.com,
// etc.), so these have to be wildcards.
const GA_BEACONS = [
  'https://*.google-analytics.com',
  'https://*.analytics.google.com',
  'https://*.googletagmanager.com',
];

const sha256 = source => `'sha256-${createHash('sha256').update(source, 'utf8').digest('base64')}'`;

/**
 * Inline <script> bodies, excluding external (src=) and data blocks
 * (application/ld+json), which CSP does not treat as executable script.
 */
export function collectInlineScriptHashes(html) {
  const hashes = [];
  const scriptTag = /<script([^>]*)>([\s\S]*?)<\/script>/g;
  let match;
  while ((match = scriptTag.exec(html)) !== null) {
    const [, attrs, body] = match;
    if (/\bsrc\s*=/.test(attrs)) continue;
    if (/type\s*=\s*["']application\/ld\+json["']/.test(attrs)) continue;
    hashes.push(sha256(body));
  }
  return hashes;
}

/**
 * Inline event-handler attributes (e.g. the font stylesheet's
 * `onload="this.media = 'all'"`). These need 'unsafe-hashes' alongside the hash —
 * without it, a hash never authorises an attribute handler.
 */
export function collectEventHandlerHashes(html) {
  const hashes = new Set();
  const handler = /\son[a-z]+\s*=\s*"([^"]*)"/g;
  let match;
  while ((match = handler.exec(html)) !== null) hashes.add(sha256(match[1]));
  return [...hashes];
}

export function buildCsp(html) {
  const scriptHashes = collectInlineScriptHashes(html);
  const handlerHashes = collectEventHandlerHashes(html);

  const directives = {
    'default-src': ["'self'"],
    // Hashes cover the gtag bootstrap and the Chatwoot loader. Presence of a hash
    // makes browsers ignore 'unsafe-inline', so it is deliberately absent here.
    'script-src': [
      "'self'",
      ...scriptHashes,
      ...(handlerHashes.length ? ["'unsafe-hashes'", ...handlerHashes] : []),
      GTM,
      CHATWOOT,
    ],
    // 'unsafe-inline' is a considered trade-off: the Chatwoot SDK injects a
    // <style> element at runtime whose contents change with their releases, so it
    // cannot be hashed here, and index.html has a pre-paint <style> block. Style
    // injection is a far weaker primitive than script injection, and script-src
    // stays strict. (React's style={{…}} writes go through CSSOM, which CSP does
    // not police, so those are unaffected either way.)
    'style-src': ["'self'", "'unsafe-inline'", FONTS_CSS],
    'img-src': ["'self'", 'data:', 'https:'],
    'font-src': ["'self'", 'data:', FONTS_FILES],
    'connect-src': ["'self'", ...GA_BEACONS, CHATWOOT],
    // The Chatwoot widget renders its panel in an iframe on its own origin.
    'frame-src': ["'self'", CHATWOOT],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
    'frame-ancestors': ["'none'"],
    'upgrade-insecure-requests': [],
  };

  return Object.entries(directives)
    .map(([directive, values]) => (values.length ? `${directive} ${values.join(' ')}` : directive))
    .join('; ');
}

export function buildHeadersFile(html) {
  return `# Generated by scripts/vite-plugin-security-headers.js — do not edit by hand.
# Applies to static asset responses only; worker.js sets its own headers on /api/*.

/*
  Content-Security-Policy: ${buildCsp(html)}
  Strict-Transport-Security: max-age=31536000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Cross-Origin-Opener-Policy: same-origin

# Content-hashed filenames, so these are safe to cache indefinitely.
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
}

export default function securityHeaders() {
  let outDir = 'dist';
  return {
    name: 'security-headers',
    // Run last so the HTML we hash is the final emitted output.
    enforce: 'post',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
    },
    closeBundle() {
      const html = readFileSync(join(outDir, 'index.html'), 'utf8');
      writeFileSync(join(outDir, '_headers'), buildHeadersFile(html), 'utf8');
    },
  };
}
